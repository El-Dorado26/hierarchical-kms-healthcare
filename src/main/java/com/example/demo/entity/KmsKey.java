package com.example.demo.entity;

import java.time.Instant;

import java.util.ArrayList;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;

@Entity
@Table(name = "kms_keys")
public class KmsKey {

    // Internal database identifier automatically generated by PostgreSQL
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Stable identifier used by applications to reference this logical KMS key
    @Column(name = "key_id", nullable = false, unique = true)
    private String keyId;

    // Metadata
    @Column(nullable = false)
    private String algorithm;

    @Column(nullable = false)
    private String purpose;

    // Lifecycle state controlling whether the key can be used
    @Column(nullable = false)
    private String status;

    // One logical KMS key can have many key versions.
    // Each version contains its own protected DEK.
    @OneToMany(
    	    mappedBy = "key",
    	    cascade = CascadeType.ALL,
    	    orphanRemoval = true
    	)
    	private List<KeyVersion> versions = new ArrayList<>();

    	@ManyToOne(optional = false)
    	@JoinColumn(name = "department_id", nullable = false)
    	private Department department;
    	
    	//to show which user created the key
    	@ManyToOne(optional = false)
    	@JoinColumn(name = "created_by_user_id", nullable = false)
    	private KmsUser createdBy;
    	//to show which user created the key

    // Stores the creation timestamp of the logical key
    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    public KmsKey() {
    }

    public Long getId() {
        return id;
    }

    public String getKeyId() {
        return keyId;
    }

    public void setKeyId(String keyId) {
        this.keyId = keyId;
    }

    public String getAlgorithm() {
        return algorithm;
    }

    public void setAlgorithm(String algorithm) {
        this.algorithm = algorithm;
    }

    public String getPurpose() {
        return purpose;
    }

    public void setPurpose(String purpose) {
        this.purpose = purpose;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public List<KeyVersion> getVersions() {
        return versions;
    }

    public void setVersions(List<KeyVersion> versions) {
        this.versions = versions;
    }

    public void addVersion(KeyVersion version) {
        versions.add(version);
        version.setKey(this);
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Department getDepartment() {
        return department;
    }

    public void setDepartment(Department department) {
        this.department = department;
    }
    //to show which user created the key
    public KmsUser getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(KmsUser createdBy) {
        this.createdBy = createdBy;
    }
}